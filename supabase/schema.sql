-- LADET — tabel riwayat peringatan.
--
-- Jalankan di Supabase: Dashboard → SQL Editor → New query → tempel → Run.
-- Firmware RX menulis ke tabel ini lewat REST (POST /rest/v1/ladet_alerts),
-- halaman /riwayat membacanya lewat anon key.

create table if not exists public.ladet_alerts (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz not null default now(),
  level           smallint    not null check (level between 1 and 3),
  level_name      text        not null,
  soil_saturation numeric(6,2),
  delta_g         numeric(6,3),
  tilt_angle      numeric(6,2),
  device          text        not null default 'LADET-RX'
);

create index if not exists ladet_alerts_created_at_idx
  on public.ladet_alerts (created_at desc);

alter table public.ladet_alerts enable row level security;

-- RX hanya perlu menulis.
drop policy if exists "ladet_alerts insert anon" on public.ladet_alerts;
create policy "ladet_alerts insert anon"
  on public.ladet_alerts
  for insert
  to anon
  with check (true);

-- Web perlu membaca untuk halaman /riwayat.
drop policy if exists "ladet_alerts select anon" on public.ladet_alerts;
create policy "ladet_alerts select anon"
  on public.ladet_alerts
  for select
  to anon
  using (true);

-- Tidak ada policy update/delete: anon tidak bisa mengubah atau menghapus.

-- Denyut harian RX: bukti perangkat masih hidup, sekaligus penjaga agar
-- project free tier tidak di-pause karena 7 hari tanpa aktivitas.
create table if not exists public.ladet_heartbeat (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  uptime_s          bigint,
  free_heap         bigint,
  reset_reason      text,
  wifi_rssi         integer,
  last_packet_age_s bigint,
  device            text not null default 'LADET-RX'
);

alter table public.ladet_heartbeat enable row level security;

drop policy if exists "ladet_heartbeat insert anon" on public.ladet_heartbeat;
create policy "ladet_heartbeat insert anon"
  on public.ladet_heartbeat
  for insert
  to anon
  with check (true);

drop policy if exists "ladet_heartbeat select anon" on public.ladet_heartbeat;
create policy "ladet_heartbeat select anon"
  on public.ladet_heartbeat
  for select
  to anon
  using (true);
